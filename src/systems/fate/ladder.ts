// Лестница Fate: числа результатов и их названия. Подписи свои (открытого русского перевода Fate Core нет).
export const LADDER: Record<number, string> = {
  8: 'Легендарно',
  7: 'Эпично',
  6: 'Фантастично',
  5: 'Превосходно',
  4: 'Отлично',
  3: 'Хорошо',
  2: 'Неплохо',
  1: 'Средне',
  0: 'Посредственно',
  [-1]: 'Плохо',
  [-2]: 'Ужасно',
};

export const signed = (n: number) => (n > 0 ? `+${n}` : n < 0 ? `−${-n}` : '0');

// «Хорошо (+3)»; выше и ниже лестницы — просто число.
export const ladderText = (n: number) => (LADDER[n] ? `${LADDER[n]} (${signed(n)})` : signed(n));
